"""
p1.py - P1 "The dashboard is empty at 08:00" (in-class lab)

Q1  total commission                      -> 4 full scales (control)
Q2  naive: every order vs every other     -> first 1,250 / 2,500 / 5,000 / 10,000 rows of Orders_10k
Q3  grouping instead of comparing         -> 4 full scales (+ the Q2 prefixes, for the identity check)

Q2 and Q3 both return ONE number: how many distinct customers bought from >= 2 different sellers on the same day.
Usage:  python p1.py            (writes p1_measurements.csv and p1_results.md)
"""
import argparse
import math
import sqlite3

from measure import (SEED, add_growth_factors, environment_line, export_to_csv, format_table,
                     measure_cold, measure_warm, run_sql)

FULL = [("Orders_10k", 10_000), ("Orders_100k", 100_000), ("ORDERS_1M", 1_000_000), ("ORDERS_10m", 10_000_000)]
PREFIXES = [1_250, 2_500, 5_000, 10_000]

Q1_SQL = "SELECT SUM(amount * 0.09) FROM {t}"

# Naive: for every order, look at the other orders. automatic_index is switched OFF, otherwise SQLite
# quietly builds a temporary index on (customer_id, order_date) and the "naive" query stops being naive.
Q2_SQL = """
SELECT COUNT(DISTINCT a.customer_id)
FROM Orders_10k AS a, Orders_10k AS b
WHERE a.order_id <= :n AND b.order_id <= :n
  AND a.customer_id = b.customer_id
  AND a.order_date  = b.order_date
  AND a.seller_id  <> b.seller_id
"""
Q2_PRAGMAS = ["PRAGMA automatic_index = OFF"]

Q3_SQL = """
SELECT COUNT(DISTINCT customer_id) FROM (
  SELECT customer_id
  FROM {t}
  WHERE order_id <= :n
  GROUP BY customer_id, order_date
  HAVING COUNT(DISTINCT seller_id) >= 2
)
"""


def bench(method, sql, params, n, db, repeats, pragmas=None):
    cold = measure_cold(sql, params, method, n, db=db, seed=SEED, repeats=3, pragmas=pragmas)
    conn = sqlite3.connect(db)
    warm = measure_warm(lambda: run_sql(conn, sql, params, pragmas or []), method, n, SEED, repeats)
    conn.close()
    assert cold.result == warm.result, f"{method} n={n}: cold/warm results differ"
    print(f"  {method:<28} n={n:>10,}  cold={cold.median:.4f}s  warm={warm.median:.4f}s  result={warm.result}",
          flush=True)
    return [cold, warm]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="Data-Class.db")
    ap.add_argument("--repeats", type=int, default=5)
    args = ap.parse_args()

    print("Environment:", environment_line())
    q1, q2, q3, q3_prefix = [], [], [], []

    print("Q1 - total commission")
    for t, n in FULL:
        q1 += bench("Q1 commission (SUM)", Q1_SQL.format(t=t), {}, n, args.db, args.repeats)

    print("Q2 - naive nested loop (first N rows of Orders_10k)")
    for n in PREFIXES:
        q2 += bench("Q2 naive (compare)", Q2_SQL, {"n": n}, n, args.db, args.repeats, Q2_PRAGMAS)

    print("Q3 - GROUP BY, full scales")
    for t, n in FULL:
        q3 += bench("Q3 grouping (GROUP BY)", Q3_SQL.format(t=t), {"n": n}, n, args.db, args.repeats)

    print("Q3 - GROUP BY on the Q2 prefixes (identity check)")
    for n in PREFIXES:
        q3_prefix += bench("Q3 grouping, prefix", Q3_SQL.format(t="Orders_10k"), {"n": n}, n, args.db, args.repeats)

    for block in (q1, q2, q3, q3_prefix):
        add_growth_factors(block)
    results = q1 + q2 + q3 + q3_prefix

    # identity check: Q2 and Q3 must give the same number on the same rows
    checks = []
    for a in [r for r in q2 if r.run == "warm"]:
        b = next(r for r in q3_prefix if r.run == "warm" and r.n == a.n)
        checks.append((a.n, a.result, b.result, a.result == b.result))
    assert all(c[3] for c in checks), f"Q2 != Q3: {checks}"

    # extrapolate Q2 from its own doubling pattern (NOT run)
    w = [r for r in q2 if r.run == "warm"]
    gfs = [r.growth_factor for r in w if r.growth_factor]
    avg_gf = math.exp(sum(math.log(g) for g in gfs) / len(gfs))    # geometric mean per doubling
    k = math.log2(avg_gf)                                            # exponent: time ~ n^k
    t10k = w[-1].median
    extrap = {n: t10k * (n / 10_000) ** k for n in (100_000, 1_000_000)}

    export_to_csv(results, "p1_measurements.csv")
    with open("p1_results.md", "w", encoding="utf-8") as f:
        f.write("# P1 measurement output (generated by p1.py)\n\n")
        f.write(f"Seed: {SEED} · Environment: {environment_line()}\n\n")
        f.write(format_table(results) + "\n\n")
        f.write("## Q2 = Q3 identity check (distinct customers)\n\n| n | Q2 | Q3 | same? |\n|---:|---:|---:|---|\n")
        for n, a, b, ok in checks:
            f.write(f"| {n:,} | {a} | {b} | {'yes' if ok else 'NO'} |\n")
        f.write(f"\n## Q2 extrapolation (not run)\n\nAverage growth per doubling: {avg_gf:.2f}x -> time ~ n^{k:.2f}\n\n")
        for n, t in extrap.items():
            f.write(f"- {n:,} rows: {t:,.0f} s (~{t/3600:.1f} h)\n")
    print("\nWrote p1_measurements.csv and p1_results.md")
    print(f"Q2 exponent k={k:.2f}; 100k ~ {extrap[100_000]:,.0f} s; 1M ~ {extrap[1_000_000]:,.0f} s")


if __name__ == "__main__":
    main()
